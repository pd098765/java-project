package package3;

public class two_arrayOf_2_different_datatypes {

	public static void main(String[] args) {

		int[] no=new int[4];
		no[0]=10;
		no[1]=11;
		no[2]=12;
		no[3]=13;
		
		String[] names=new String[4];
		names[0]="pooja";
		names[1]="prasad";
		names[2]="kamal";
		names[3]="pavan";
		
		for(int i=0;i<no[i];i++) {
			System.out.println("No: "+no[i]+"|Names:"+names[i]);
		}
		

	}

}
